# ── ユーティリティ関数 ────────────────────────────────────────────────────────
def gen_phone(area_code, seq):
    """都道府県の市外局番 + 連番から電話番号生成"""
    local1 = 1000 + (seq % 8999)
    local2 = 1000 + ((seq * 37 + 5678) % 9000)
    return f"{area_code}-{local1}-{local2}"

def gen_email(cat_code, seq):
    return f"info@{cat_code}-{seq:05d}.co.jp"

def gen_url(cat_code, seq):
    return f"https://www.{cat_code}-{seq:05d}.co.jp/"

def gen_address(pref_name, cities, seq):
    city = cities[seq % len(cities)]
    block = (seq % 10) + 1
    num1  = (seq % 8) + 1
    num2  = (seq % 5) + 1
    return f"{pref_name}{city}{block}-{num1}-{num2}"

